"""
Nucleic-acid residue names that are not (or not only) wwPDB component ids but occur in
pdb2pqr/Amber output and in older files, with their class and plain parent base:
RNA `RA RC RG RU` and DNA `DA DC DG DT`, each also with the terminal suffixes `5`, `3` and
`N` (`RA5`, `RG3`, `DAN`, ...). [`component`](@ref) reports them as nucleotides
(`:rna`/`:dna`, `"rna linking"`/`"dna linking"`, `parent` the plain base: `A C G U` or
`DA DC DG DT`, and the formula and hydrogen count of that base) **before** consulting the
table, because the table also uses several of them (`DA5`, `RG3`, ...) for unrelated
ligands. The one exception is `RU`, which the table has as ruthenium: it is left to the
table, and a residue named so is taken as uracil only by the backbone-atom test of
`Hydrogenator.hydrogenation_choice`. The CHARMM/old free-base ids `ADE CYT GUA THY URA` are
not here: the wwPDB uses them for the free bases (non-polymers).
"""
const AMBER_NUCLEIC_NAMES = let d = Dict{String,Tuple{Symbol,String}}()
    for (n, base) in (("RA", "A"), ("RC", "C"), ("RG", "G"), ("RU", "U")),
        suf in ("", "5", "3", "N")

        n * suf == "RU" || (d[n*suf] = (:rna, base))
    end
    for n in ("DA", "DC", "DG", "DT"), suf in ("5", "3", "N")
        d[n*suf] = (:dna, n)
    end
    # plain DA DC DG DT are components of the table already
    d
end

"""
Legacy residue ids (CHARMM and older files) of the nucleotide bases, with the base they
stand for: `ADE` A, `GUA` G, `CYT` C, `URI` U, `THY` T. The wwPDB uses these ids for the
free bases (non-polymer ligands), so [`component`](@ref) keeps them `:other`; a residue
under one of these names is a nucleotide only when it carries the sugar-phosphate backbone
(`legacy_nucleotides`): it has a `P` atom, or at least [`BACKBONE_MIN`](@ref) of the
[`BACKBONE_ATOMS`](@ref) and its chain has at least two such residues. `DAD DCY DGU DTH`
are not here: the table has them as D-amino acids and a sugar.
"""
const LEGACY_NUCLEOTIDE_NAMES =
    Dict("ADE" => "A", "GUA" => "G", "CYT" => "C", "URI" => "U", "THY" => "T")

"""
The sugar-phosphate backbone atoms of a nucleotide residue (primes spelled `'`; the old
`*` is read as `'`), the evidence for a nucleic acid whose residue names are unknown or
legacy: a residue with at least [`BACKBONE_MIN`](@ref) of them is a nucleotide.
"""
const BACKBONE_ATOMS = ("P", "O5'", "C5'", "C4'", "O4'", "C3'", "C2'", "C1'")

"How many [`BACKBONE_ATOMS`](@ref) make an unknown or legacy-named residue a nucleotide."
const BACKBONE_MIN = 4

"""
# Fields
- `_name::String`: structure identifier (e.g. PDB ID or file stem).
- `_elms::Vector{String}`: per-atom element symbol, length n.
- `_n::Int`: atom count; set at construction, never recomputed.
- `_cart::Matrix{Float64}, (3, n)`: centred Cartesian coordinates (x, y, z).
- `_sph::Matrix{Float64}, (3, n)`: spherical coordinates (r, theta, phi),
    sharing `_cart`'s column index.
- `_radii::Lazy{Vector{Float64}}`: per-atom isolated van der Waals radius
    (AtomicRadii), length n.
- `_vols::Lazy{Vector{Float64}}`: per-atom geometrically-computed excluded
    volume from [`excluded_volume`](@ref), length n.
- `_r_max::Lazy{Float64}`: largest per-atom radius in `_radii`.
- `_tree::Lazy{KDTree}`: KDTree over `_cart`, shared across neighbour queries.
"""
struct Molecule <: SphereCloud
    _name  :: String
    _elms  :: Vector{String}
    _n     :: Int                   # atom count; set at construction, never recomputed
    _cart  :: Matrix{Float64}       # (3, n) centred (x, y, z)
    _sph   :: Matrix{Float64}       # (3, n) (r, theta, phi)
    _radii :: Lazy{Vector{Float64}}
    _vols  :: Lazy{Vector{Float64}}
    _r_max :: Lazy{Float64}         # largest per-atom radius
    _tree  :: Lazy{KDTree}          # KDTree over _cart; shared across neighbour queries
end


const _FIXTURE_DIR = joinpath(@__DIR__, "..", "..", "fixtures", "experiments", "SASDNS2")
const _DATA_PATH   = joinpath(_FIXTURE_DIR, "experimental_data", "SASDNS2.dat")
const _PDB_PATH    = joinpath(_FIXTURE_DIR, "SASDNS2_fit2_2DN1_tetramer.pdb")
const _FIT_PATH    = joinpath(_FIXTURE_DIR, "SASDNS2_fit2.fit")

# ---------------------------------------------------------------------------
#                                 Source
# ---------------------------------------------------------------------------
#
# SASBDB SASDNS2: native human haemoglobin (HbA, alpha UniProt P69905 and beta P68871,
# 15.0 and 15.9 kDa per chain, the alpha2-beta2 tetramer, SASBDB experimental MW 53 kDa)
# at 5 mg/ml in Ringer's lactate solution, pH 6.5. The native (PEG-free) reference curve
# of a study of PEG-conjugated haemoglobin.
#
# Publication (SASBDB): Svergun D, Ekström F, Vandegriff K, Malavalli A, Baker D, Nilsson
# C, Winslow R, "Solution Structure of Poly(ethylene) Glycol-Conjugated Hemoglobin
# Revealed by Small-Angle X-Ray Scattering: Implications for a New Oxygen Therapeutic",
# Biophys J 2008, DOI 10.1529/biophysj.107.114314. Entry:
# https://www.sasbdb.org/data/SASDNS2/. The paper could NOT be reached (the fetch failed),
# so the conditions below are the SASBDB entry metadata only.
#
# Instrument (SASBDB): EMBL beamline X33, DORIS III (DESY, Hamburg), MAR 345 image plate,
# sample-detector distance 2.5 m, wavelength 0.15 nm (SASBDB `xray_energy` is null, so the
# energy is hc/λ ≈ 8266 eV); 3 frames of 60 s; measured 2006-02-19 (the .fit header:
# fred_016.dat minus Avrag06.dat, divided by 5). Neither SASBDB nor the paper gives a cell
# temperature: 25 °C is assumed (owner decision 2026-11-13; the paper names only
# "Ringer's lactate", whose USP recipe is used below).
#
# Curve units: the SASBDB .dat is in nm⁻¹ (angular_unit "1/nm"; s_min 0.094 and s_max
# 4.988 nm⁻¹), converted to Å⁻¹ (÷10) below. The signal-to-noise stays above about 4 over
# the whole range and no point is non-positive; the whole curve is fitted (the
# depositor's curve runs to 0.48 Å⁻¹).
#
# Model and depositor fit: fit2 is CRYSOL (SASBDB: software CRYSOL, no version) against
# "PDB 2DN1" (human haemoglobin, "identical"; SASBDB lists the model mass as 32.19 kDa,
# i.e. the alpha-beta dimer of the asymmetric unit). The depositor's fit is nevertheless
# the TETRAMER: its header reads "2DN1.PDB  Dro:0.005  Ra:1.780  RGE:24.59  RGT:24.31
# Vol: 85764.", values that fit the alpha2-beta2 tetramer rather than a 32 kDa dimer, and
# the measured mass is 53 kDa. SASBDB's model file could not be downloaded (404), so
# SASDNS2_fit2_2DN1_tetramer.pdb was BUILT from the RCSB file 2DN1.pdb (kept beside it,
# unchanged): waters and ANISOU lines removed, chains A and B kept, and chains C and D
# generated by applying the file's own BIOMT operator 2 (y, x, -z) to them, atoms
# renumbered; 4552 ATOM and HETATM records (4 haem HEM, 4 OXY, 4 MBN, all known
# components, kept by the loader; no hydrogens), with the closest distance between a
# generated and an original atom 2.49 Å (no overlap). That the depositor used exactly this
# assembly is inferred from the header's numbers, not stated. fit1 is GASBOR (chi2 8.35)
# and fit3 is CRYSOL against 2DN2 (chi2 12.24); neither is used.
#
# The fit header reads "Chi:2.763" and SASBDB's chi_square_value is 7.634169. Here 2.763²
# = 7.634, so SASBDB's number is the square of the header; recomputing a reduced χ² from
# the .fit columns (q, I_exp, I_fit) against the .dat σ gives 2.70, so the header number
# is the χ² and SASBDB's value is its square. refChi2 is therefore the header value 2.763
# (recomputed 2.70, from the points whose q matches exactly; the .fit has no σ column).
# The .fit file has THREE columns: q (Å⁻¹), I_exp, I_fit, with a leading q grid at which
# I_exp is a placeholder and only I_fit is meaningful (all `Reference` uses), so the
# reference curve is column 3.

# ---------------------------------------------------------------------------

qvals, iExp, σ_exp = _readCurve(_DATA_PATH)

# qvals are in nm⁻¹; must convert to Å⁻¹.
qvals = qvals ./ NM_INV_PER_ANGSTROM_INV
checkQAngstrom(qvals)

# ---------------------------------------------------------------------------
#                            Solution conditions
# ---------------------------------------------------------------------------

const PH, σ_PH = 6.5, PH_METER_SIGMA   # SASBDB: pH 6.5 (no pH uncertainty stated)

const ENERGY_EV     = HC_EV_ANGSTROM / 1.5   # ≈ 8266 eV, SASBDB wavelength 0.15 nm
const TEMPERATURE_C = 25.0                    # assumed (owner), neither source gives it

# Buffer as deposited (SASBDB buffer name): "Ringer's lactate solution", pH 6.5; no
# composition is given on the entry and the paper was not reached, so the composition is
# ASSUMED to be the USP lactated Ringer's solution (per litre: NaCl 6.0 g, KCl 0.3 g,
# CaCl2·2H2O 0.2 g, sodium lactate 3.1 g (anhydrous, 112.06 g/mol)): NaCl 102.7 mM, KCl
# 4.0 mM, CaCl2 1.36 mM and sodium lactate 27.7 mM. Other products differ by a few
# percent; this is the closest default and it is flagged. The measured macromolecule is
# deliberately NOT a solute (see BulkElectronDensity.Solute).
#
# Every species is fully dissociated at pH 6.5 (lactic acid pK_a 3.86), so there is no
# buffer to speciate and no titrant counter-ion; the pH is only used to place the
# hydrogens. σ ±5 % on each assumed concentration.
const SOLUTES = Solute[
    NonBiological(0.1027, 0.0051, "sodium chloride"),   # 102.7 mM NaCl (USP), ±5%
    NonBiological(0.0040, 0.0002, "potassium chloride"),   # 4.0 mM KCl (USP), ±5%
    NonBiological(0.00136, 0.00007, "calcium chloride"),   # 1.36 mM CaCl2 (USP), ±5%
    NonBiological(0.0277, 0.0014, "sodium lactate"),   # 27.7 mM sodium lactate (USP), ±5%
]

# ---------------------------------------------------------------------------
#                       Forward-model / sampler wiring
# ---------------------------------------------------------------------------

# The whole .dat is fitted (q 0.0094-0.4988 Å⁻¹); the depositor's fit2 ends at 0.4838 Å⁻¹,
# so refChi2 is not like for like.

# The spherical-harmonic band limit lMax is not set here: `seedModel` takes it from
# the diameter of the scatterer cloud and the largest fitted q (ceil(qMax * D)), and
# bins the curve to the Shannon channels that diameter allows (see `rebin` there).

# The deposited model has no hydrogens: pdb2pqr/PROPKA place them at PH.
const ADD_HYDROGENS = true

"""
    fitSubset() -> (q, I, σ)

`qvals`/`I_exp`/`σ_exp` restricted to `σ_exp > 0`.
(`seedModel` bins the curve and drops the bins with non-positive intensity.)
"""
function fitSubset()
    keep = findall(i -> σ_exp[i] > 0, eachindex(qvals))
    return qvals[keep], iExp[keep], σ_exp[keep]
end

# Builds the Seed that `runSasdns2` samples. It is separate only because
# the developer tools in test/utils/ build a fit's Seed without running
# the fit; if you are reading this script as an example you can skip it:
# `runSasdns2` below is the whole story (build the seed, then sample it).
function seedSasdns2(; seed::Integer = SAMPLER_SEED)
    qFit, iFit, σ_fit = fitSubset()

    Random.seed!(seed)
    s = BAYSOL.seedModel(
        LocalPathSource(_PDB_PATH), ENERGY_EV, qFit, iFit, σ_fit, PH, σ_PH, SOLUTES;
        addHydrogens = ADD_HYDROGENS, t = TEMPERATURE_C,
    )
    return s, (s.shannon.q, s.shannon.I, s.shannon.σ)   # the binned curve the fit saw
end

function runSasdns2(;
    nSamples::Int = N_SAMPLES,
    nAdapt::Int = N_ADAPT,
    seed::Integer = SAMPLER_SEED,
)
    s, data = seedSasdns2(; seed)
    res = BAYSOL.runModel(s, nSamples, nAdapt)
    return res, s.fw.formFactorLog, s.fw.nAtoms, data
end

result, formFactorLog, nAtoms, (qFit, iFit, σ_fit) = runSasdns2()

fit, divergenceRate, mapResult, quantileResult = result

# `results` writes the figures (terminal plots, pgfplots .tex), the workbook and this

# run's section of the folder's run log; `refChi2` is the depositor's χ² for the log.
# The .fit file is CRYSOL's (fit2) with THREE columns: q (Å⁻¹), I_exp, I_fit (no σ).
crysol = readdlm(_FIT_PATH; skipstart = 1)
reference = BAYSOL.Reference(
    "CRYSOL fit2",
    Float64.(crysol[:, 1]),
    Float64.(crysol[:, 3]),
)
BAYSOL.results(
    result, (qFit, iFit, σ_fit);
    dir = @__DIR__, name = "res", references = reference,
    formFactorLog = formFactorLog, nAtoms = nAtoms,
    refChi2 = "CRYSOL 2.763",
    runLog = true,
)

# `@__DIR__` (this SASDNS2/ folder), not the caller's cwd.

BAYSOL.printSummary(result)

;; The Results table of test/fitting_tests/README.md,
;; generated from the reports instead of tabulated by hand.
;;
;;     bb results-table                print the table
;;     bb results-table ID [ID ...]
;;         print only the rows of those fitting tests
;;     bb results-table --update
;;         rewrite the table in test/fitting_tests/README.md
;;     bb results-table --check
;;         exit 1 if the table in that README is not up to date
;;     bb results-table --tsv FILE
;;         write every quantity read from every run (not only the table's
;;         columns) to FILE, one tab-separated row per res*.xlsx
;;
;; One row per `test/fitting_tests/*/res*.xlsx` (the workbook `results` writes,
;; with the `res*_timings.txt` beside it for the timings): the MAP χ² (the `chi2` row
;; of the `map` sheet, on the measured q grid whatever the binning of the fit, so it
;; is comparable with the depositor's), the MAP δρ₁, δρ₂, δρ₃, the profiled c1 and
;; the share of divergent transitions, all read from the workbook. The depositor's χ²
;; column cannot be computed; it comes from test/fitting_tests/depositor_chi2.tsv
;; (one line per run). A run whose depositor text is the same as the row above it
;; (same entry) prints ″, as the members of one deposited multi-model fit do.
;;
;; Bold marks a parameter at a hard prior bound, c1 profiling saturation, or a chain
;; with more than 5 % divergent transitions. "At a bound" means within 0.05 of the
;; δρ₁/δρ₂ bounds [-10, 2], and within 0.1 of the δρ₃ bounds [-ρ̄ₑ/0.03, (φ_max -
;; 1)·ρ̄ₑ/0.03] (ρ̄ₑ taken as the run's MAP ρₑ). These tolerances were chosen so the
;; rule reproduces every bold mark of the table as it was tabulated by hand.
;;
;; --update replaces what lies between the two marker comments in the README.
;; --check compares what lies there with the table generated from the reports, cell
;; by cell (column padding and spacing are ignored, so a formatter cannot make it
;; fail) and exits 1, naming the rows that differ, when they are not the same.
;; Shared helpers are in common.clj and the report parser in report.clj.

;; The tool's own folder is the classpath, so `common` and `report` load from any
;; working directory.
(ns results-table
    (:require [babashka.classpath :refer [add-classpath]]
        [babashka.cli :as cli]
        [babashka.fs :as fs]
        [clojure.string :as str]))

(add-classpath (str (fs/parent (fs/absolutize *file*))))

(require '[common :as c] '[report] '[workbook])

;; Bounds of the sampled contrasts, as in
;; src/Inference/Inference.jl (BOUNDS_δρ₁₂, UNIT_OF_δρ, φ_max).
(def ^:private lower-bound-δρ₁₂ -10.0)
(def ^:private dro-upper 2.0)
(def ^:private unit-of-δρ 0.03)
(def ^:private phi-max 1.25)

;; How close to a bound counts as "at" it (see the header).
(def ^:private tol-dro12 0.05)
(def ^:private tol-dro3 0.1)

;; Divergence share above which a chain is flagged.
(def ^:private divergent-flag 0.05)

;; The marker comments around the table in the README; the begin marker must read
;; exactly as the one there.
(def ^:private begin-mark
    (str "<!-- results-table:begin (generated by bb results-table; the "
        "depositor column comes from depositor_chi2.tsv) -->"))
(def ^:private end-mark "<!-- results-table:end -->")

(def ^:private who "bb results-table")

(defn ^:private report-paths
    "Every run's workbook, in path order (the order of the table's rows)."
    []
    (->> (fs/glob (c/in-root c/fit-dir) "*/res*.xlsx")
        (map str)
        sort))

(defn ^:private run-label
    "The run label as the table shows it: \"SASDBS6 fit2_model1\", or \"SASDZC6 —\"
    for a report without a tag."
    [path]
    ;; res.xlsx -> "", res_fit1.xlsx -> "fit1"
    (let [tag (-> (fs/file-name path)
                fs/strip-ext
                (subs 3)
                (str/replace #"^_+" ""))]
        (str (fs/file-name (fs/parent path)) " " (if (seq tag) tag "—"))))

(defn ^:private read-run
    "The parsed numbers of the run whose workbook is at `path` (with its timing file)."
    [path]
    (report/parse-run (workbook/read-file path)
        (let [t (report/timings-path path)]
            (if (fs/exists? t) (c/slurp8 t) ""))))

(defn ^:private depositors
    "Depositor text for every run, from the side file: map of label -> text."
    []
    (into {}
        (for [line (str/split (c/slurp8 (c/in-root c/fit-dir
                            "depositor_chi2.tsv"))
                    #"\n"
                    -1)
                :when (not (or (= line "") (str/starts-with? line "#")))
                ;; label, tab, text; a text-less line has an empty one
                :let [[run text] (str/split line #"\t" -1)]]
            [run (or text "")])))

(defn ^:private minus
    "A number with a true minus sign, as the README prints them."
    [s]
    (str/replace s "-" "−"))

(defn ^:private bold
    "`**text**` when `flag` is true."
    [text flag]
    (if flag (str "**" text "**") text))

(defn ^:private at-bound?
    "Is the contrast value `v` within `tol` of either end of [lo, hi]?"
    [v lo hi tol]
    (or (>= v (- hi tol)) (<= v (+ lo tol))))

(defn ^:private row
    "The cells of one table row from a parsed report."
    [run r depositor]
    (let [[rho d1 d2 d3 c1 div chi2] (map #(parse-double (r %))
                [:rho_e :d1 :d2 :d3 :c1 :div :chi2_cmp])
            ;; δρ₃ is bounded by the cavity occupancy, scaled by the run's own ρₑ
            d3-lo (/ (- rho) unit-of-δρ)
            d3-hi (/ (* (- phi-max 1) rho) unit-of-δρ)
            contrast (fn [d lo hi tol]
                (bold (minus (c/fmt "%.2f" d)) (at-bound? d lo hi tol)))
            c1-text (c/fmt "%.3f" c1)]
        [run (c/fmt "%.3g" chi2) depositor
            (contrast d1 lower-bound-δρ₁₂ dro-upper tol-dro12)
            (contrast d2 lower-bound-δρ₁₂ dro-upper tol-dro12)
            (contrast d3 d3-lo d3-hi tol-dro3)
            (if (= (r :sat) "true") (str "**" c1-text " (saturated)**") c1-text)
            (bold (if (zero? div) "0" (str (c/fmt "%.1f" (* div 100)) " %"))
                (> div divergent-flag))]))

(defn ^:private table-lines
    "The table as markdown lines (header, separator, one row per report in path order),
    for the fitting tests in `only` (all of them when empty). The \"″\" repeat marker
    follows the rows actually shown."
    [only]
    (let [deps (depositors)
            runs (for [path (report-paths)
                    :let [label (run-label path)
                        id (first (str/split label #"\s+"))]
                    :when (or (empty? only) (some #{id} only))]
                {:path path,
                    :label label,
                    :id id,
                    :dep (or (deps label)
                        (throw (ex-info (str "no depositor line for '"
                                    label
                                    "' in depositor_chi2.tsv")
                                {})))})]
        (concat
            [(str "| Run | χ² (MAP) | depositor's χ² (method) | δρ₁ | δρ₂ | δρ₃ "
                    "| c1 | divergences |") "|---|---|---|---|---|---|---|---|"]
            ;; each row next to the one shown before it, for the repeat marker
            (map (fn [prev {:keys [path label id dep]}]
                    (let [same? (and prev (= id (:id prev)) (= dep (:dep prev)))
                            r (read-run path)
                            cells (row label r (if same? "″" dep))]
                        (str "| " (str/join " | " cells) " |")))
                (cons nil runs)
                runs))))

(defn ^:private tsv-text
    "Every parsed quantity of every report as tab-separated text: a header line (run,
    then the union of the keys in first-seen order), then one row per res*.xlsx in path
    order; a key a report lacks is an empty cell."
    []
    (let [runs (for [p (report-paths)] [(run-label p) (read-run p)])
            ks (distinct (mapcat (comp :order meta second) runs))
            ;; a number in its canonical form ("3.20" -> 3.2); no tab or newline
            cell
            (fn [r k]
                (str/replace (c/num-str (c/as-number (get r k ""))) #"[\t\n]" " "))]
        (str/join "\n"
            (cons (str/join "\t" (cons "run" (map name ks)))
                (for [[label r] runs]
                    (str/join "\t" (cons label (map #(cell r %) ks))))))))

(defn ^:private table-cells
    "The cells of the rows of a markdown table, trimmed with runs of white space
    collapsed to one space. The separator row (|---|---|) is skipped, so column
    padding does not matter."
    [text]
    (for [line (map str/trim (str/split text #"\n" -1))
            :when (and (str/starts-with? line "|")
                (not (re-matches #"\|[\s:|-]+" line)))]
        (mapv #(str/replace (str/trim %) #"\s+" " ")
            (str/split (subs line 1 (dec (count line))) #"\|" -1))))

(defn ^:private readme-region
    "The README, its text and the span between the two marker comments
    ({:readme :text :from :to}); an error, exit status 1, if a marker is missing."
    []
    (let [readme (c/in-root c/fit-dir "README.md")
            text (c/slurp8 readme)
            b (str/index-of text begin-mark)
            e (str/index-of text end-mark)]
        (when-not (and b e (< b e))
            (throw (ex-info (str who
                        ": the markers\n  " begin-mark
                        "\n  " end-mark
                        "\nare not in " readme)
                    {})))
        {:readme readme, :text text, :from (+ b (count begin-mark)), :to e}))

(defn ^:private check-table
    "Is the README table the generated one? Prints the differing rows and returns 1 if
    not, else 0."
    [table]
    (let [{:keys [readme text from to]} (readme-region)
            have (vec (table-cells (subs text from to)))
            want (vec (table-cells table))
            show #(str/join " | " %)]
        (if (= have want)
            (do (println (str "Results table in "
                        readme
                        " is up to date ("
                        (count want)
                        " rows)"))
                0)
            (binding [*out* *err*]
                (println (str "Results table in " readme
                        " is out of date; regenerate it"
                        " with: bb results-table --update"))
                ;; the first ten rows that differ
                (doseq [i (take 10
                            (filter #(not= (get have %) (get want %))
                                (range (max (count have) (count want)))))]
                    (println (str "  row " i
                            " in the README : " (show (get have i))))
                    (println (str "  row " i
                            " generated    : " (show (get want i)))))
                1))))

(defn ^:private update-readme
    "Replaces what lies between the marker comments of the README by `table`."
    [table]
    (let [{:keys [readme text from to]} (readme-region)
            updated (str (subs text 0 from) "\n" table "\n" (subs text to))]
        (if (= updated text)
            (println "README.md already up to date")
            (do (spit readme updated :encoding "UTF-8")
                (println "updated the Results table in" readme)))))

(defn run
    "The tool's main program for the argument list `argv`; returns the exit status."
    [argv]
    (let [{:keys [args opts]} (cli/parse-args
                argv
                {:coerce {:update :boolean,
                        :check :boolean,
                        :help :boolean,
                        :h :boolean,
                        :tsv :string},
                    :restrict [:update :check :help :h :tsv],
                    :error-fn (fn [{:keys [msg]}] (c/fail who msg))})
            {update? :update, check? :check, tsv-file :tsv} opts
            known (set (c/ids))]
        (if (or (:help opts) (:h opts))
            (c/usage)
            (do (doseq [id args
                        :when (not (known id))]
                    (c/fail who (str "no fitting test '" id "'")))
                (cond (and update? check?)
                    (c/fail who "give --update or --check, not both")
                    (and (or update? check?) (seq args))
                    (c/fail
                        who
                        "--update and --check cover the whole table; give no ID")
                    (and tsv-file (or update? check? (seq args)))
                    (c/fail who "--tsv stands alone")
                    tsv-file
                    (do (spit tsv-file (str (tsv-text) "\n") :encoding "UTF-8")
                        (println "wrote" tsv-file))
                    :else (let [table (str/join "\n" (table-lines args))]
                        (cond check? (check-table table)
                            update? (update-readme table)
                            :else (println table))))))))

;; Run only when executed as a script, so the functions can be loaded for testing.
(when (= *file* (System/getProperty "babashka.file"))
    (c/main run *command-line-args*))

"""

# --- the result sets
#
# A result set is a sorted map of path -> parsed run (see Report). Sorted, so that sums run
# over the fits in the same order whatever the source.

const ResultSet = OrderedDict{String,Run}

sorted_set(pairs) = ResultSet(sort!(collect(pairs); by = first))

# The key of a run in a result set: its folder and its name, the section title of a log
# (`test/fitting_tests/SASDBS6/fit2_model1`; the folder alone for a run named after it) or
# the path of a text report without its extension, so the same fit has the same key at
# every revision.
function run_key(path, title)
    dir = dirname(path)
    title === nothing && return replace(String(path), r"\.txt$" => "")
    return title == basename(dir) ? dir : string(dir, "/", title)
end

# The runs of the log at `path` with the text `text`, as `(key, run)` pairs.
log_runs(path, text) = [(run_key(path, title), r) for (title, r) in parse_log(text)]

# The parsed runs of every fitting test at `rev`: the runs of its logs (`<ID>.LOG`), or,
# in a revision from before the logs, its `res*.txt` text reports.
function git_reports(rev)::ResultSet
    paths = split_lines(git("ls-tree", "-r", "--name-only", rev, FIT_DIR))
    logs = filter(p -> occursin(Regex("^" * FIT_DIR * "/[^/]+/[^/]+\\.LOG\$"), p), paths)
    texts =
        isempty(logs) ?
        filter(
            p -> occursin(Regex("^" * FIT_DIR * "/[^/]+/res[^/]*\\.txt\$"), p), paths) :
        String[]
    pairs = Pair{String,Run}[]
    for p in logs, (k, r) in log_runs(p, git("show", string(rev, ":", p)))
        push!(pairs, k => r)
    end
    for p in texts
        push!(pairs, run_key(p, nothing) => parse_report(git("show", string(rev, ":", p))))
    end
    return sorted_set(pairs)
end

# The same for the files in the working tree.
function tree_reports()::ResultSet
    pairs = Pair{String,Run}[]
    base = in_root(FIT_DIR)
    for d in readdir(base)
        dir = joinpath(base, d)
        isdir(dir) || continue
        for f in readdir(dir)
            endswith(f, ".LOG") || continue
            p = relpath(joinpath(dir, f), root())
            for (k, r) in log_runs(p, slurp8(joinpath(dir, f)))
                push!(pairs, k => r)
            end
        end
    end
    return sorted_set(pairs)
end

# --- small numeric and formatting helpers

present(v) = !(v === nothing || v == "")

# The non-empty values of `k` over a map of reports, as numbers.
column(reports, k) = filter(present, [as_number(get(r, k, "")) for r in values(reports)])

# Sum of `k` over the reports, or `nothing` if no report has it (older formats lack some
# fields).
function total(reports, k)
    xs = column(reports, k)
    return isempty(xs) ? nothing : foldl(+, xs; init = 0.0)
end

or_zero(v) = present(v) ? as_number(v) : 0

mean(xs) = foldl(+, xs) / Float64(length(xs))

"Median of the numbers `xs`."
function median(xs)
    v = sort(collect(xs))
    n = length(v)
    return isodd(n) ? v[n÷2+1] : (v[n÷2] + v[n÷2+1]) / 2.0
end

"Quantile `q` (0..1) of `xs`, by linear interpolation between order statistics."
function pct(xs, q)
    v = sort(collect(xs))
    last_i = length(v) - 1
    k = last_i * q
    lo = trunc(Int, k)
    hi = lo + 1 < last_i ? lo + 1 : last_i
    a = v[lo+1]
    return a + (v[hi+1] - a) * (k - lo)
end

"`x` with `decimals` decimals and thousands separators: 4782.4 0 -> \"4,782\"."
function commas(x, decimals)
    s = fmt("%.$(decimals)f", x)
    while true
        t = replace(s, r"^(-?\d+)(\d{3})" => s"\1,\2"; count = 1)
        t == s && return s
        s = t
    end
end

"`v` by the conversion `spec`, or \"-\" when it is empty."
dash(spec, v) = present(v) ? fmt(spec, v) : "-"

"\"x.xx\" ratio of two numbers, or n/a when either is missing or zero."
function ratio(numer, denom)
    any(x -> x === nothing || x == "" || (x isa Number && iszero(x)), (numer, denom)) &&
        return "n/a"
    return fmt("%.2f", Float64(numer) / denom) * "x"
end

# The median of `xs` by `spec`, or "-" when there are none.
med(xs, spec) = isempty(xs) ? "-" : fmt(spec, median(xs))

# `f(xs)` of the known values of `k`, by `spec`, or "-" when no report has it.
function stat(reports, k, f, spec)
    xs = column(reports, k)
    return isempty(xs) ? "-" : fmt(spec, f(xs))
end

p90(xs) = pct(xs, 0.9)
n_where(pred, xs) = count(pred, xs)

# Prints a markdown table row.
row(cells...) = println("| ", join(string.(cells), " | "), " |")

# Prints the header and rule lines of a markdown table.
function head(cells)
    row(join(cells, " | "))
    println("|", repeat("---|", length(cells)))
end

heading(text) = println("\n### ", text, "\n")


# What the fitting tests found, read from the run logs: the Results table of the
# fitting-test README (`bysl results table`) and the comparison of two or more revisions
# (`bysl results compare`).
module Results

using ..Common

module Table

using ...Common
using ...Report

const WHO = "bysl results table"

const USAGE = """
The Results table of test/fitting_tests/README.md, from the run logs.

    bysl results table [ID ...]
    bysl results table --update | --check | --tsv FILE

    (none)      print the table (only the rows of the IDs given)
    --update    rewrite the table in the README
    --check     exit 1 if the README table is stale (cells compared, not padding)
    --tsv FILE  write every quantity of every run to FILE

Bold marks a parameter at a prior bound, a saturated c1, or over 5 % divergences.
"""

# Bounds of the sampled contrasts, as in src/Inference/Params.jl (BOUNDS_δρ₁₂, φ_max) and
# UNIT_OF_δρ of PhysicalConstants.jl.
const LOWER_BOUND_DRO12 = -10.0
const DRO_UPPER = 2.0
const UNIT_OF_DRO = 0.03
const PHI_MAX = 1.25

# How close to a bound counts as "at" it (see the header).
const TOL_DRO12 = 0.05
const TOL_DRO3 = 0.1

# Divergence share above which a chain is flagged.
const DIVERGENT_FLAG = 0.05

# The marker comments around the table in the README; the begin marker must read exactly
# as the one there.
const BEGIN_MARK =
    "<!-- results-table:begin (generated by bysl results table from the run " *
    "logs; the depositor column is the ref_chi2 row of each run) -->"
const END_MARK = "<!-- results-table:end -->"

# Every fitting test's run log, in path order (the order of the table's rows).
function log_paths()
    base = in_root(FIT_DIR)
    found = String[]
    for d in readdir(base)
        dir = joinpath(base, d)
        isdir(dir) || continue
        for f in readdir(dir)
            endswith(f, ".LOG") && push!(found, joinpath(dir, f))
        end
    end
    return sort(found)
end

# The run label as the table shows it: "SASDBS6 fit2_model1", or "SASDZC6 —" for the run
# named after its folder `id`, whose section title is `title`.
run_label(id, title) = string(id, " ", title == id ? "—" : title)

# The runs of every log, in path order and, within a log, in file order: named tuples of
# the label as the table shows it, the folder's id and the run (see `parse_log`).
function runs()
    out = NamedTuple{(:label, :id, :run),Tuple{String,String,Run}}[]
    for path in log_paths()
        id = basename(dirname(path))
        for (title, r) in parse_log(slurp8(path))
            push!(out, (label = run_label(id, title), id = id, run = r))
        end
    end
    return out
end

# A number with a true minus sign, as the README prints them.
minus(s) = replace(s, "-" => "−")

# `**text**` when `flag` is true.
bold(text, flag) = flag ? "**$text**" : text

# Is the contrast value `v` within `tol` of either end of [lo, hi]?
at_bound(v, lo, hi, tol) = v >= hi - tol || v <= lo + tol

# The cells of one table row from a parsed run.
function row(label, r, ref_chi2)
    rho, d1, d2, d3, c1, div, chi2 = (parse(Float64, r[k]) for k in
                              (:rho_e, :d1, :d2, :d3, :c1, :div, :chi2_cmp))
    # δρ₃ is bounded by the cavity occupancy, scaled by the run's own ρₑ
    d3_lo = -rho / UNIT_OF_DRO
    d3_hi = (PHI_MAX - 1) * rho / UNIT_OF_DRO
    contrast(d, lo, hi, tol) = bold(minus(fmt("%.2f", d)), at_bound(d, lo, hi, tol))
    c1_text = fmt("%.3f", c1)
    return [label, fmt("%.3g", chi2), ref_chi2,
        contrast(d1, LOWER_BOUND_DRO12, DRO_UPPER, TOL_DRO12),
        contrast(d2, LOWER_BOUND_DRO12, DRO_UPPER, TOL_DRO12),
        contrast(d3, d3_lo, d3_hi, TOL_DRO3),
        r[:sat] == "true" ? "**$c1_text (saturated)**" : c1_text,
        bold(div == 0 ? "0" : fmt("%.1f", div * 100) * " %", div > DIVERGENT_FLAG)]
end

"""
    table_lines(only) -> Vector{String}

The table as markdown lines (header, separator, one row per run in log order), for the
fitting tests in `only` (all of them when empty).
"""
function table_lines(only)
    shown = [x for x in runs() if isempty(only) || x.id in only]
    lines = [
        "| Run | χ² (MAP) | depositor's χ² (method) | δρ₁ | δρ₂ | δρ₃ | c1 | divergences |",
        "|---|---|---|---|---|---|---|---|"]
    prev = nothing
    for x in shown
        dep = x.run[:ref_chi2]
        same = prev !== nothing && x.id == prev.id && dep == prev.run[:ref_chi2]
        cells = row(x.label, x.run, same ? "″" : dep)
        push!(lines, "| " * join(cells, " | ") * " |")
        prev = x
    end
    return lines
end

"""
    tsv_text() -> String

Every parsed quantity of every run as tab-separated text: a header line (run, then the
union of the keys in first-seen order), then one row per run in log order; a key a run
lacks is an empty cell.
"""
function tsv_text()::String
    rs = [(x.label, x.run) for x in runs()]
    ks = unique(reduce(vcat, [collect(keys(r)) for (_, r) in rs]; init = Symbol[]))
    # a number in its canonical form ("3.20" -> 3.2); no tab or newline
    cell(r, k) = replace(num_str(as_number(get(r, k, ""))), r"[\t\n]" => " ")
    lines = [join(vcat("run", string.(ks)), "\t")]
    for (label, r) in rs
        push!(lines, join(vcat(label, [cell(r, k) for k in ks]), "\t"))
    end
    return join(lines, "\n")
end

# The cells of the rows of a markdown table, trimmed with runs of white space collapsed to
# one space.
function table_cells(text)
    out = Vector{Vector{String}}()
    for line in strip.(split(text, '\n'; keepempty = true))
        (startswith(line, "|") && !occursin(r"^\|[\s:|-]+$", line)) || continue
        inner = chop(line; head = 1, tail = 1)
        push!(
            out,
            [replace(strip(c), r"\s+" => " ") for c in split(inner, '|';
                keepempty = true)],
        )
    end
    return out
end

# The README, its text and the span between the two marker comments; an error, exit status
# 1, if a marker is missing.
function readme_region()
    readme = in_root(FIT_DIR, "README.md")
    text = slurp8(readme)
    b = findfirst(BEGIN_MARK, text)
    e = findfirst(END_MARK, text)
    (b === nothing || e === nothing || first(b) >= first(e)) && throw(
        ToolError(
            "$WHO: the markers\n  $BEGIN_MARK\n  $END_MARK\nare not in $readme", 1),
    )
    return (; readme, text, from = last(b), to = first(e))
end

# The part of `text` after byte index `i` up to (not including) byte index `j`.
between(text, i, j) = i + 1 > j - 1 ? "" : text[nextind(text, i):prevind(text, j)]

# Is the README table the generated one? Prints the differing rows and returns 1 if not,
# else 0.
function check_table(table)
    (; readme, text, from, to) = readme_region()
    have = table_cells(between(text, from, to))
    want = table_cells(table)
    if have == want
        println("Results table in ", readme, " is up to date (", length(want), " rows)")
        return 0
    end
    println(stderr, "Results table in ", readme, " is out of date; regenerate it with: ",
        "bysl results table --update")
    # the first ten rows that differ
    n = max(length(have), length(want))
    shown = 0
    for i in 0:(n-1)
        shown >= 10 && break
        h = i < length(have) ? have[i+1] : nothing
        w = i < length(want) ? want[i+1] : nothing
        h == w && continue
        println(stderr, "  row ", i, " in the README : ", fmt_row(h))
        println(stderr, "  row ", i, " generated    : ", fmt_row(w))
        shown += 1
    end
    return 1
end

fmt_row(cells) = cells === nothing ? "nil" : join(cells, " | ")

# Replaces what lies between the marker comments of the README by `table`.
function update_readme(table)
    (; readme, text, from, to) = readme_region()
    updated = text[1:from] * "\n" * table * "\n" * text[to:end]
    if updated == text
        println("README.md already up to date")
    else
        spit8(readme, updated)
        println("updated the Results table in ", readme)
    end
    return 0
end

# The options of the command line: `(; args, update, check, help, tsv)`.
function parse_args(argv)
    update = check = help = false
    tsv = nothing
    args = String[]
    i = 1
    while i <= length(argv)
        a = argv[i]
        if a == "--update"
            update = true
        elseif a == "--check"
            check = true
        elseif a in ("--help", "-h")
            help = true
        elseif a == "--tsv"
            i == length(argv) && fail(WHO, "Missing value for option --tsv")
            tsv = argv[i+1]
            i += 1
        elseif startswith(a, "-") && length(a) > 1
            fail(WHO, "Unknown option: $a")
        else
            push!(args, a)
        end
        i += 1
    end
    return (; args, update, check, help, tsv)
end

"The tool's main program for the argument list `argv`; returns the exit status."
function run(argv::Vector{String})::Int
    (; args, update, check, help, tsv) = parse_args(argv)
    if help
        usage(USAGE)
        return 0
    end
    known = Set(ids())
    for id in args
        id in known || fail(WHO, "no fitting test '$id'")
    end
    update && check && fail(WHO, "give --update or --check, not both")
    (update || check) && !isempty(args) &&
        fail(WHO, "--update and --check cover the whole table; give no ID")
    tsv !== nothing && (update || check || !isempty(args)) &&
        fail(WHO, "--tsv stands alone")
    if tsv !== nothing
        spit8(tsv, tsv_text() * "\n")
        println("wrote ", tsv)
        return 0
    end
    table = join(table_lines(args), "\n")
    check && return check_table(table)
    update && return update_readme(table)
    println(table)
    return 0
end

end

module Compare

using JSON3

# Timing totals over all common fits, one column per revision plus "last vs each other"
# ratios.
function timing_table(agg, names)
    cur = last(names)
    others = names[1:(end-1)]
    wall = total(agg[cur], :wall)
    row("(all fits, summed)", join(names, " | "),
        join(("$cur vs $o" for o in others), " | "), "% of wall")
    println("|---|", repeat("---|", length(names) + length(others) + 1))
    for (label, k) in TIMING_ROWS
        v = Dict(n => total(agg[n], k) for n in names)
        denom = v[cur]
        cells = String[]
        for n in names
            x = v[n]
            push!(
                cells,
                x === nothing ? "-" :
                k == :leapfrog ? commas(x * 1e-6, 2) :
                commas(x, x < 10 ? 2 : 0) * " s",
            )
        end
        share =
            (denom !== nothing && wall !== nothing && k != :leapfrog) ?
            fmt("%.1f", 100 * denom / wall) * " %" : "-"
        row(label, join(cells, " | "), join((ratio(v[o], denom) for o in others), " | "),
            share)
    end
    println("\n(ratio > 1: the last column is faster / does less work than that revision)")
end

# How many common fits got better / worse / stayed within 1 % in `latest` against `old`.
function quality(latest, old, label, cur)
    pairs = Tuple{Any,Any}[]
    for (k, r) in latest
        a = as_number(get(r, :chi2_cmp, ""))
        b = haskey(old, k) ? as_number(get(old[k], :chi2_cmp, "")) : nothing
        haskey(old, k) && a isa Number && b isa Number && push!(pairs, (a, b))
    end
    lower = n_where(p -> p[1] < 0.99 * p[2], pairs)
    higher = n_where(p -> p[1] > 1.01 * p[2], pairs)
    println("χ² of ", cur, " vs ", label, " (", length(pairs),
        " common fits, ±1 % counts as unchanged): ", lower, " lower, ", higher, " higher, ",
        length(pairs) - lower - higher, " unchanged")
end

# One row of the distribution table: fit quality and parameter distributions of a set of
# reports.
function distribution(reports, label)
    chi2 = column(reports, :chi2_cmp)
    rs = collect(values(reports))
    row(label, length(reports), med(chi2, "%.2f"),
        isempty(chi2) ? "-" :
        fmt("%.2f", pct(chi2, 0.25)) * " / " * fmt("%.2f", pct(chi2, 0.75)),
        # more than 1 % divergent transitions
        n_where(r -> or_zero(get(r, :div, "")) > 0.01, rs),
        # c1 at its bound
        n_where(r -> !(get(r, :sat, "") in ("", "false", "0")), rs),
        n_where(>(3), abs.(column(reports, :z3))),
        med(column(reports, :d3), "%+.2f"),
        # deep trees
        n_where(r -> or_zero(get(r, :steps, "")) > 100, rs),
        med(column(reports, :steps), "%.1f"))
end

# --- the expanded tables: fit quality spread, sampler health, MAP search, sizes, posterior
# widths

# The χ² distribution of a column: spread, geometric mean and how many fits are above a
# few thresholds.
function chi2_row(reports, label)
    x = column(reports, :chi2_cmp)
    g(v) = fmt("%.3g", v)
    row(label, length(reports), g(pct(x, 0)), g(pct(x, 0.25)), g(median(x)),
        g(pct(x, 0.75)),
        g(pct(x, 0.9)), g(pct(x, 1)), g(exp(mean(log.(x)))), n_where(<(1.5), x),
        n_where(>(5), x), n_where(>(10), x))
end

# Sampler health of a column: acceptance, tree depth and steps, E-BFMI, divergences, and
# (reports with chains) the worst R-hat and the smallest ESS.
function sampler_row(reports, label)
    col(k) = column(reports, k)
    rhat = col(:rhat_max)
    div = col(:div)
    dropped = isempty(col(:chains_total)) ? nothing : total(reports, :chains_dropped)
    row(label, med(col(:accept), "%.3f"), stat(reports, :accept, minimum, "%.3f"),
        med(col(:depth), "%.2f"), stat(reports, :depth_max, maximum, "%d"),
        med(col(:steps), "%.1f"), stat(reports, :steps, p90, "%.1f"),
        med(col(:ms_per_step), "%.2f"), stat(reports, :ebfmi, minimum, "%.2f"),
        n_where(<(0.3), col(:ebfmi)), n_where(>(0), div),
        isempty(div) ? "-" : fmt("%.3f", 100 * mean(div)),
        isempty(rhat) ? "-" :
        fmt("%.3f", maximum(rhat)) * " (" * string(n_where(>(1.01), rhat)) * ")",
        med(col(:ess_min), "%.0f"), med(col(:ess_tail_min), "%.0f"),
        dropped === nothing ? "-" : trunc(Int, dropped),
        n_where(>(1), col(:modes)), stat(reports, :mode_share_max, minimum, "%.3f"))
end

# The MAP search of a column: modes, starts that converged, its time and its share of the
# wall clock.
function map_row(reports, label)
    ok = column(reports, :map_starts_ok)
    m = total(reports, :map_s)
    w = total(reports, :wall_ex)
    row(label, med(column(reports, :map_modes), "%.0f"),
        n_where(>(1), column(reports, :map_modes)),
        isempty(ok) ? "-" : fmt("%.2f", mean(ok)),
        med(column(reports, :map_s), "%.3f"),
        (m !== nothing && w !== nothing) ? fmt("%.1f", 100 * m / w) * " %" : "-")
end

# What the fits were (a rebinned or re-sized problem is not comparable 1:1): medians of
# the problem sizes.
function size_row(reports, label)
    row(
        label,
        [
            med(column(reports, k), spec) for (k, spec) in
            [(:n_atoms, "%.0f"), (:lMax, "%.0f"), (:n_q_raw, "%.0f"), (:n_q, "%.0f"),
                (:dmax, "%.1f"), (:n_samples, "%.0f"), (:n_adapt, "%.0f")]
        ]...,
    )
end

# One parameter's posterior: the median MAP z-score, how many fits have it beyond 3 sigma
# of the prior, and the width of the quantile interval in prior standard deviations (z_hi
# - z_lo): median, p10, p90.
function width_row(reports, label, prefix)
    key(suffix) = Symbol(prefix, suffix)
    zmap = column(reports, key("_Z_MAP"))
    w = Any[]
    for r in values(reports)
        lo = as_number(get(r, key("_Z_QUANT_LO"), ""))
        hi = as_number(get(r, key("_Z_QUANT_HI"), ""))
        lo isa Number && hi isa Number && push!(w, hi - lo)
    end
    row(label, isempty(zmap) ? "-" : fmt("%.2f", median(zmap)),
        isempty(zmap) ? 0 : n_where(z -> abs(z) > 3, zmap),
        isempty(w) ? "-" : fmt("%.3f", median(w)),
        isempty(w) ? "-" : fmt("%.3f", pct(w, 0.1)),
        isempty(w) ? "-" : fmt("%.3f", pct(w, 0.9)))
end

shown(path) = replace(path, FIT_DIR * "/" => "")

# The eight worst fits of the judged column by `k`, with every column's cell (made by
# `cell` from a report).
function worst(title, sets, names, k, cell)
    ranked = sort([(path, or_zero(get(r, k, ""))) for (path, r) in sets[last(names)]];
        by = last, rev = true, alg = MergeSort)
    isempty(ranked) || iszero(last(first(ranked))) && return
    println("\n", title, " (columns: ", join(names, " | "), ")")
    for (path, _) in ranked[1:min(8, end)]
        cells = [haskey(sets[n], path) ? cell(sets[n][path]) : "-" for n in names]
        println("  ", rpad(shown(path), 42), " ", join(cells, " | "))
    end
end

cell_nuts(r) =
    dash("%.1f", get(r, :steps, "")) * " / " * dash("%.1f", get(r, :nuts, "")) * "s"
cell_chi2(r) =
    fmt("%.3g", or_zero(get(r, :chi2_cmp, ""))) * " / " *
    dash("%.4f", get(r, :div, ""))
cell_rhat(r) =
    dash("%.3f", get(r, :rhat_max, "")) * " / " * dash("%.0f", get(r, :ess_min, "")) *
    " / " * dash("%.0f", get(r, :ess_tail_min, ""))

# Every expanded table, over the common fits (`agg`: name -> reports) and the judged
# column's full sets.
function detail_tables(agg, sets, names)
    cur = last(names)
    each(f) = foreach(n -> f(agg[n], n), names)
    heading("Fit quality, spread")
    head(["", "fits", "min", "Q1", "median", "Q3", "p90", "max", "geo. mean", "χ² <1.5",
        "χ² >5", "χ² >10"])
    each(chi2_row)
    heading("Sampler health")
    head(["", "median accept", "min accept", "median depth", "max depth",
        "median steps/iter",
        "p90 steps/iter", "median ms/step", "min E-BFMI", "E-BFMI <0.3",
        "fits with divergences", "mean divergence %", "R-hat max (fits >1.01)",
        "median min bulk ESS", "median min tail ESS", "chains dropped", "fits with >1 mode",
        "smallest share of the top mode"])
    each(sampler_row)
    heading("MAP search")
    head(["", "median modes", "fits with >1 mode", "mean starts ok", "median MAP s",
        "share of wall"])
    each(map_row)
    heading("Problem sizes (medians)")
    head(["", "atoms", "lMax", "measured points", "fitted points", "Dmax Å", "iterations",
        "warm-up"])
    each(size_row)
    heading("Posterior of $cur (z in prior standard deviations)")
    head([
        "parameter",
        "median MAP z",
        "fits |z|>3",
        "median width",
        "width p10",
        "width p90",
    ])
    for (label, prefix) in
        [("ρₑ", "rho_e"), ("δρ₁", "dro1"), ("δρ₂", "dro2"), ("δρ₃", "dro3")]
        width_row(agg[cur], label, prefix)
    end
    heading("Worst fits")
    worst("Most NUTS work: steps/iter / NUTS seconds", sets, names, :steps, cell_nuts)
    worst("Highest χ²: χ² / divergent share", sets, names, :chi2_cmp, cell_chi2)
    worst("Least converged chains: R-hat max / min bulk ESS / min tail ESS", sets, names,
        :rhat_max, cell_rhat)
end

# --- the benchmark comparison (--bench)

# Stage rows of the benchmark tables: (label, prefix of the stage names summed into that
# row).
const STAGES = [("forward_cache", "forward_cache"), ("MAP search", "MAP search"),
    ("NUTS", "NUTS  ("), ("c1 re-profile", "per-draw c1 re-profile"),
    ("propka", "propka"),
    ("pdb2pqr", "pdb2pqr"), ("components", "components"), ("classify", "classify"),
    ("structure checks", "structure checks"), ("heavy atoms", "heavy atoms"),
    ("modified nucleotide hydrogens", "modified nucleotide hydrogens"),
    ("modified amino acid hydrogens", "modified amino acid hydrogens")]

# Seconds of `field` (:stage_seconds, :stage_compile or :stage_gc) summed over the stages
# named `prefix`*, `nothing` when the fit has no such stage (an older run, or a stage that
# did not apply to that structure).
function stage_total(fit, field, prefix)
    vs = [
        v for (stage, v) in zip(get(fit, :stage_name, []), get(fit, field, []))
        if startswith(stage, prefix)
    ]
    return isempty(vs) ? nothing : foldl(+, vs; init = 0.0)
end

# Seconds of compile time inside the timed stages (those at depth 1) of a fit.
compile_in_stages(fit) = foldl(+,
    [cmp for (depth, cmp) in zip(fit[:stage_depth],
        fit[:stage_compile]) if depth == 1]; init = 0.0)

# Prints one table row of the benchmark report: `getter` is given the fit of a run and
# returns a number; a run lacking the fit shows "-".
function bench_row(runs, names, spec, label, getter)
    cells = Any[]
    for n in names
        fits = get(runs[n], :fit, nothing)
        fit = fits === nothing ? nothing : get(fits, Symbol(spec), nothing)
        push!(cells, fit === nothing ? nothing : getter(fit))
    end
    row(label, join((dash("%.2f", c) for c in cells), " | "),
        join((ratio(c, last(cells)) for c in cells[1:(end-1)]), " | "))
end

# Side-by-side report of benchmark JSON files from `bysl fits bench` (the last file is the
# one judged).
function bench_main(files)::Int
    if length(files) == 1
        tag = latest_release()
        base = tag === nothing ? nothing : baseline_for(tag)
        if base === nothing
            println(stderr, "no benchmark baseline for the latest release (",
                something(tag, "none found"), ") in test/baselines/; name the file to ",
                "compare with, as: bysl results compare --bench OLD.json NEW.json ",
                "(test/baselines/README.md)")
            return 1
        end
        println("baseline: ", basename(base), " (the latest release, ", tag, ")")
        files = vcat([base], files)
    end
    # a run is named after its file
    names = [first(splitext(basename(f))) for f in files]
    runs = Dict(n => JSON3.read(slurp8(f)) for (n, f) in zip(names, files))
    cur = last(names)
    for n in names
        m = runs[n][:meta]
        println(n, ": ", m[:state], " state, ", m[:git_rev], ", ", m[:host], ", Julia ",
            m[:julia], ", ", m[:cpu])
    end
    # results from different machines or cold vs warm state are not comparable
    for (field, warning) in [(:host, "results from different hosts are not comparable"),
        (:state, "mixing cold and warm results; compare like with like")]
        length(unique([get(runs[n][:meta], field, nothing) for n in names])) > 1 &&
            println("WARNING: ", warning)
    end
    println(
        "\ninstall (instantiate + precompile): ",
        join(
            [
                n * ": " *
                fmt("%.1f", as_number(runs[n][:install][:precompile_s]))[1:end] * " s" for
                n in names
            ], ", "),
    )
    fit_keys(n) = String[string(k) for k in keys(runs[n][:fit])]
    specs = sort(unique(reduce(vcat, [fit_keys(n) for n in names])))
    for spec in specs
        r(label, getter) = bench_row(runs, names, spec, label, getter)
        top(k) = f -> as_number(f[k])
        total_of(which) = f -> as_number(f[which][:total_s])
        println("\n== ", spec)
        row(
            "seconds",
            join(names, " | "),
            join(("$cur vs $n" for n in names[1:(end-1)]), " | "),
        )
        println("|---|", repeat("---|", 2 * length(names) - 1))
        r("process wall", top(:process_wall_s))
        r("using BAYSOL", top(:using_baysol_s))
        r("tooling load (not product)", top(:tooling_load_s))
        # first fit = includes JIT compilation
        r("FIRST FIT total (seed + run)", total_of(:first))
        r("  first - steady (JIT and first-use cost)",
            f -> as_number(f[:first][:total_s]) - as_number(f[:second][:total_s]))
        r("  compile inside the timed stages", f -> compile_in_stages(f[:first]))
        for (label, prefix) in STAGES
            r("  first: " * label, f -> stage_total(f[:first], :stage_seconds, prefix))
        end
        # steady fit = second fit in the same process, everything compiled
        r("STEADY FIT total (seed + run)", total_of(:second))
        for (label, prefix) in STAGES[1:4]
            r("  steady: " * label, f -> stage_total(f[:second], :stage_seconds, prefix))
            r("  steady: " * label * " GC", f -> stage_total(f[:second], :stage_gc, prefix))
        end
    end
    println(
        "\n(ratio > 1: the last file is faster; first fit includes JIT, steady fit does ",
        "not; compare cold with cold only)")
    return 0
end

# --- the stage notes

# The stages whose notes the notes table shows, in the order of the report.
const NOTE_STAGES = ["components", "classify", "propka", "pdb2pqr",
    "modified nucleotide hydrogens", "modified amino acid hydrogens", "heavy atoms"]

# The note of the stage `nm` in `report` (a variant such as `pdb2pqr (mixed, propka)`
# counts as `pdb2pqr`), or "".
function stage_note(report, nm)
    for (k, v) in report.stage_notes
        startswith(k, nm) && return v
    end
    return ""
end

# Is a fit worth a line of the notes table: not protein-only, or a cache missed, or a
# component downloaded.
function notable(report)
    notes = collect(values(report.stage_notes))
    return any(n -> startswith(n, "[nucleic"), notes) ||
           any(n -> startswith(n, "[mixed"), notes) ||
           any(n -> occursin("cache miss", n), notes) ||
           or_zero(get(report, :comp_dwnld, "")) > 0
end

# The notes of the judged column's fits that are not plain protein runs with every cache
# hit: what the nucleotide stages found, and which lookups missed.
function notes_table(reports, cur)
    heading("Stage notes of $cur")
    rows = [
        vcat(shown(path), [stage_note(r, s) for s in NOTE_STAGES])
        for (path, r) in reports if notable(r)
    ]
    if isempty(rows)
        println("(every fit is protein-only with all caches hit, or has no notes)")
    else
        head(vcat("fit", NOTE_STAGES))
        foreach(cells -> row(cells...), rows)
    end
end

# --- the CSV files

# Writes `file`: a header `fit,<name>:<key>,...`, then one line per fit of the judged
# column, with `cell` giving the text of a report value (nothing: blank).
function write_csv(file, sets, names, keys_, header_key, cell)
    latest = sets[last(names)]
    io = IOBuffer()
    println(
        io,
        join(vcat("fit", [string(n, ":", header_key(k)) for n in names for k in keys_]),
            ","),
    )
    for path in keys(latest)
        cells = String[]
        for n in names, k in keys_
            r = get(sets[n], path, nothing)
            push!(cells, cell(r === nothing ? nothing : get(r, k, nothing)))
        end
        println(io, shown(path), ",", join(cells, ","))
    end
    spit8(file, String(take!(io)))
end

# --- the main program

# The command line: `(; revs, no_tree, bench, csv, csv_all)`.
function parse_args(argv)
    revs = String[]
    no_tree = bench = false
    csv = csv_all = nothing
    i = 1
    while i <= length(argv)
        a = argv[i]
        if a == "--no-tree"
            no_tree = true
        elseif a == "--bench"
            bench = true
        elseif a == "--csv"
            csv = i < length(argv) ? argv[i+1] : nothing
            i += 1
        elseif a == "--csv-all"
            csv_all = i < length(argv) ? argv[i+1] : nothing
            i += 1
        elseif startswith(a, "--")
            println(stderr, "usage: ", WHO, " [REV ...] [--no-tree] [--csv FILE] ",
                "[--csv-all FILE] | --bench FILE.json ...")
            throw(ToolError("", 2))
        else
            push!(revs, a)
        end
        i += 1
    end
    return (; revs, no_tree, bench, csv, csv_all)
end

# The result sets to compare: `(names, sets)`, one per revision then the working tree.
function load_sets(revs, no_tree)
    names = String[]
    sets = Dict{String,ResultSet}()
    for rev in revs
        if resolve_rev(rev) === nothing
            println(stderr, "unknown git revision '", rev, "'; tags here: ",
                join(split_lines(strip(git("tag", "--list"))), ", "))
            throw(ToolError("", 1))
        end
        # the same rev twice stays distinguishable
        label = rev in names ? string(rev, "#", length(names)) : rev
        reports = git_reports(rev)
        if isempty(reports)
            println("warning: no fitting-test reports at ", rev, "; skipped")
        else
            push!(names, label)
            sets[label] = reports
        end
    end
    no_tree && return names, sets
    push!(names, "working tree")
    sets["working tree"] = tree_reports()
    return names, sets
end

"The tool's main program for the argument list `argv`; returns the exit status."
function run(argv::Vector{String})::Int
    if any(a -> a in ("--help", "-h"), argv)
        usage(USAGE)
        return 0
    end
    (; revs, no_tree, bench, csv, csv_all) = parse_args(argv)
    bench && return bench_main(revs)
    if isempty(revs)
        tag = latest_release()
        if tag === nothing
            println(stderr, "no release tag (v<digit>...) in this ",
                "repository; name the revisions to compare")
            return 1
        end
        println("baseline: ", tag, ", the latest release (name other revisions to ",
            "compare with those instead)")
        revs = [tag]
    end
    names, sets = load_sets(revs, no_tree)
    if length(names) < 2
        println(stderr, "need at least two result sets to compare")
        return 1
    end
    cur = last(names)
    # only fits that have a report in every column are aggregated, so the columns are
    # comparable
    common = [
        path for path in keys(sets[first(names)]) if all(n -> haskey(sets[n], path), names)
    ]
    if isempty(common)
        println(stderr, "no fit has a report in every column")
        return 1
    end
    agg = Dict(n => sorted_set([p => sets[n][p] for p in common]) for n in names)
    latest = sets[cur]
    println("Reports: ", join(["$n=$(length(sets[n]))" for n in names], ", "))
    println("Everything below except the per-fit list and the CSV is aggregated over the ",
        length(common), " fits that have a report in every column.\n")
    # --- the report
    timing_table(agg, names)
    notes_table(agg[cur], cur)
    println("\n| | fits | median χ² | χ² Q1 / Q3 | >1 % divergent | c1 pinned",
        " | MAP >3σ from δρ₃ prior | median δρ₃ | fits >100 steps/iter",
        " | median steps/iter |")
    println("|---|---|---|---|---|---|---|---|---|---|")
    foreach(n -> distribution(agg[n], n), names)
    println()
    foreach(n -> quality(agg[cur], agg[n], n, cur), names[1:(end-1)])
    detail_tables(agg, sets, names)
    # every parsed key of every column (the keys of the judged column's first report)
    csv_all === nothing || write_csv(csv_all, sets, names,
        collect(keys(latest[first(keys(latest))])), string,
        v -> num_str(something(v, "")))
    # the fixed list of per-fit numbers, blank where a revision lacks a value
    csv === nothing || write_csv(csv, sets, names,
        [:chi2_cmp, :steps, :depth, :nuts,
            :wall_ex, :div, :c1, :d1, :d2, :d3, :z3, :n_modes],
        k -> k == :chi2_cmp ? "chi2" : string(k), v -> present(v) ? fmt("%.6g", v) : "")
    return 0
end


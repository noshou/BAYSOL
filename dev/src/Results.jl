const WHO = "bysl results compare"

const USAGE = """
Compares fitting-test results between git revisions and the working tree.

    bysl results compare [REV ...] [--no-tree] [--csv FILE] [--csv-all FILE]
    bysl results compare --bench [OLD.json] NEW.json

    REV         a git revision; with none, the latest release (a v<digit> tag)
    --no-tree   leave out the working tree (the last REV is then judged)
    --csv       per-fit numbers to FILE
    --csv-all   every parsed key to FILE
    --bench     compare `bysl fits bench` results; one file is compared with the
